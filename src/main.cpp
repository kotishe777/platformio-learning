/*
 * Lesson 2.5 — Servo 01: fixed positions with hardware LEDC PWM.
 * Board: ESP32-S3 DevKitC-1 (N16R8), Arduino Core 3.x (pioarduino).
 * Servo signal on GPIO4, 50 Hz, 14-bit resolution.
 * Moves 30 -> 90 -> 150 degrees; LEDC keeps generating pulses during delay().
 *
 * ============================================================================
 * СХЕМА ПІДКЛЮЧЕННЯ
 * ============================================================================
 *
 * Дві зони живлення, СПІЛЬНА ЛИШЕ ЗЕМЛЯ:
 *   - зона 3.3 В: ESP32 живиться від USB комп'ютера;
 *   - зона 5 В:   серво живиться від модуля живлення макетки (перемичка на 5V).
 *
 * Дроти серво (SG90 / MG90S):
 *   коричневий / чорний          = GND
 *   червоний (СЕРЕДНІЙ)          = «+» 5 В
 *   помаранчевий / жовтий / білий = Signal
 *   Підказка: найтемніший = GND, середній = «+», найсвітліший = Signal.
 *
 * ---------------------------------------------------------------------------
 * СХЕМА А — серво без логічного аналізатора
 * ---------------------------------------------------------------------------
 *   1. Модуль живлення +5V   -> шина «+» макетки
 *   2. Модуль живлення GND   -> шина «−» макетки
 *   3. Серво «+» (середній)  -> шина «+» (5 В)
 *   4. Серво GND             -> шина «−»
 *   5. Серво Signal          -> ESP32 GPIO4
 *   6. ESP32 GND             -> шина «−»     (СПІЛЬНА ЗЕМЛЯ — обов'язково!)
 *   7. ESP32 USB             -> комп'ютер
 *
 *   Модуль +5V ---> шина «+» ---> Серво «+»
 *   Модуль GND ---> шина «−» ---> Серво GND
 *                      ^
 *   ESP32 GND ---------+            (спільна земля)
 *   ESP32 GPIO4 ----------------> Серво Signal
 *   ESP32 USB ------------------> Комп'ютер
 *
 * ---------------------------------------------------------------------------
 * СХЕМА Б — серво + логічний аналізатор (усе зі схеми А, плюс:)
 * ---------------------------------------------------------------------------
 *   8.  Аналізатор CH1 (D0)  -> ESP32 GPIO4 (той самий рядок, що й Signal)
 *   9.  Аналізатор GND       -> шина «−»
 *   10. Аналізатор USB       -> комп'ютер
 *
 *   ESP32 GPIO4 --+-------------> Серво Signal
 *                 +-------------> Аналізатор CH1 (D0)
 *   Шина «−» -------------------> Аналізатор GND
 *
 *   PulseView: fx2lafw, 1 MHz, 5 M samples, декодер Timing на D0.
 *   Очікую: період ≈ 20 мс; HIGH ≈ 1166 / 1500 / 1833 мкс (30° / 90° / 150°).
 *
 * Порядок увімкнення: перевірити дроти -> USB ESP32 -> модуль живлення ON.
 */

// ============================================================================
// 1. ПІДКЛЮЧЕННЯ БІБЛІОТЕК
// ============================================================================

// Arduino.h — «головний набір інструментів» Arduino:
// Serial, delay(), ledcAttach(), ledcWrite() та інше.
#include <Arduino.h>

// cstdint дає типи з точно відомим розміром:
//   uint8_t  — ціле число без знака, 8 біт  (0 … 255)
//   uint16_t — ціле число без знака, 16 біт (0 … 65 535)
//   uint32_t — ціле число без знака, 32 біти (0 … 4 294 967 295)
// У мікроконтролерах важливо знати, скільки місця займає число,
// щоб не було «переповнення» (як одометр, що після 999999 скидається на 000000).
#include <cstdint>

// ============================================================================
// 2. НАЛАШТУВАННЯ (КОНСТАНТИ)
// ============================================================================
// constexpr = «значення відоме вже під час компіляції й ніколи не змінюється».
// Компілятор просто підставить числа в код — це не займає оперативну пам'ять.

// Пін, до якого під'єднано СИГНАЛЬНИЙ провід серво (помаранчевий/жовтий/білий).
// GPIO4 на ESP32-S3 — звичайний пін без спеціальних ролей при старті, тому безпечний.
constexpr uint8_t SERVO_PIN = 4;

// Частота PWM: 50 імпульсів за секунду.
// Саме таку частоту «слухають» стандартні хобі-серво (SG90, MG90S тощо).
constexpr uint32_t PWM_FREQ_HZ = 50;

// Роздільність PWM у бітах = на скільки «поділок» ділимо один період.
// 14 біт → 2^14 = 16 384 поділки. Це максимум, який LEDC на ESP32-S3
// дає при 50 Гц. Що більше поділок, то точніше задаємо ширину імпульсу.
// 🧪 МІНІ-ЕКСПЕРИМЕНТ: заміни на 12 і порівняй duty та ширину на аналізаторі.
constexpr uint8_t PWM_RESOLUTION_BITS = 14;

// Тривалість одного періоду в мікросекундах:
// 1 секунда = 1 000 000 мкс; 1 000 000 / 50 = 20 000 мкс = 20 мс.
// «UL» = unsigned long: кажемо компілятору рахувати у великому типі без знака.
constexpr uint32_t PWM_PERIOD_US = 1000000UL / PWM_FREQ_HZ;

// Кількість поділок у періоді: 1 << 14 — це «зсунути одиничку на 14 позицій вліво»,
// тобто 2 у 14-му степені = 16 384.
// Одна поділка = 20 000 / 16 384 ≈ 1.22 мкс.
constexpr uint32_t PWM_STEPS = 1UL << PWM_RESOLUTION_BITS;

// Межі ширини імпульсу для нашого серво.
// 1000 мкс (1.0 мс) = 0°, 2000 мкс (2.0 мс) = 180°.
// Це ТИПОВІ значення: деякі серво мають 500…2500 мкс. Ми навмисно
// беремо обережний діапазон, щоб не впиратися в механічні упори.
constexpr uint16_t SERVO_MIN_US = 1000;
constexpr uint16_t SERVO_MAX_US = 2000;

// ============================================================================
// 3. ДОПОМІЖНА ФУНКЦІЯ: мікросекунди → «поділки» (duty)
// ============================================================================
// LEDC не розуміє мікросекунд, він рахує ПОДІЛКИ (тіки лічильника).
// Тому треба перевести бажану ширину імпульсу в кількість поділок:
//
//            pulseUs × PWM_STEPS
//   duty = ───────────────────────
//               PWM_PERIOD_US
//
// Приклад для 1500 мкс: 1500 × 16384 / 20000 = 1228.8 → округлюємо до 1229.
//
// Навіщо «+ PWM_PERIOD_US / 2»?
// Ділення цілих чисел у C++ просто ВІДКИДАЄ дробову частину (1228.8 → 1228).
// Якщо перед діленням додати половину дільника, вийде звичайне шкільне
// округлення до найближчого (1228.8 → 1229).
//
// Чи не переповниться uint32_t? Найбільше проміжне значення:
// 2000 × 16384 = 32 768 000 — це набагато менше за межу ≈ 4.29 мільярда. Безпечно.
uint32_t pulseToDuty(uint32_t pulseUs) {
    return (pulseUs * PWM_STEPS + PWM_PERIOD_US / 2) / PWM_PERIOD_US;
}

// ============================================================================
// 4. ГОЛОВНА ФУНКЦІЯ: «стань на кут angle»
// ============================================================================
void setServoAngle(uint8_t angle) {
    // Запобіжник: кут не може бути більшим за 180°.
    // (Менше 0 бути не може в принципі, бо uint8_t не має від'ємних значень.)
    if (angle > 180) angle = 180;

    // Переводимо кут у мікросекунди звичайною пропорцією:
    //   0°   → 1000 мкс
    //   90°  → 1000 + 90 × 1000 / 180 = 1500 мкс
    //   180° → 2000 мкс
    // static_cast<uint32_t>(angle) — «розширюємо» маленьке 8-бітне число до
    // 32-бітного ПЕРЕД множенням, щоб результат точно вмістився.
    // Ділення на 180 — цілочисельне: для 30° вийде 166 (а не 166.67), тобто 1166 мкс.
    //
    // ВАЖЛИВО: це КОМАНДА «стань сюди», а не виміряний кут.
    // Серво не повідомляє, де воно насправді.
    const uint32_t pulseUs = SERVO_MIN_US
        + (static_cast<uint32_t>(angle) * (SERVO_MAX_US - SERVO_MIN_US)) / 180;

    // Мікросекунди → поділки для LEDC.
    const uint32_t duty = pulseToDuty(pulseUs);

    // ЄДИНА «справжня робота» процесора: записати одне число в регістр LEDC.
    // Після цього рядка апаратура САМА кожні 20 мс видає імпульс потрібної ширини,
    // процесор у цьому більше не бере участі.
    //
    // У Core 3.x ledcWrite(пін, duty) повертає true/false (вдалося чи ні).
    // Знак «!» означає «НЕ»: якщо НЕ вдалося — друкуємо помилку.
    if (!ledcWrite(SERVO_PIN, duty)) {
        Serial.println("LEDC: не вдалося встановити duty");
    }

    // Друкуємо в монітор, що саме ми наказали:
    //   %u  — unsigned (ціле без знака)
    //   %lu — unsigned long (довге ціле без знака)
    // static_cast<...> тут — щоб тип числа точно відповідав «шаблону» у printf.
    Serial.printf("angle=%u deg, pulse=%lu us, duty=%lu\n",
                  static_cast<unsigned>(angle),
                  static_cast<unsigned long>(pulseUs),
                  static_cast<unsigned long>(duty));
}

// ============================================================================
// 5. setup() — виконується ОДИН раз після ввімкнення або перезапуску
// ============================================================================
void setup() {
    // Вмикаємо Serial (монітор) на швидкості 115200 біт/с.
    // Ця ж швидкість стоїть у platformio.ini → monitor_speed.
    // Порада: перший рядок (angle=90) інколи «губиться», бо USB-монітор
    // ще не встиг під'єднатися. Це нормально.
    Serial.begin(115200);

    // ledcAttach(пін, частота, роздільність) — одна функція Core 3.x,
    // яка робить три речі:
    //   1) знаходить вільний PWM-канал LEDC;
    //   2) налаштовує для нього апаратний таймер LEDC на 50 Гц і 14 біт;
    //   3) під'єднує вихід каналу до GPIO4.
    // Повертає true, якщо все вдалося.
    if (!ledcAttach(SERVO_PIN, PWM_FREQ_HZ, PWM_RESOLUTION_BITS)) {
        Serial.println("ERROR: ledcAttach failed");
        // Без PWM серво не працюватиме, тож далі йти немає сенсу.
        // Нескінченний цикл «зупиняє» програму, а delay(1000) не дає їй
        // марно навантажувати процесор.
        while (true) delay(1000);
    }

    // Безпечний старт — центр (90°). З центру серво рушає найменше,
    // тож немає ризику, що воно різко «вдариться» в упор.
    setServoAngle(90);
}

// ============================================================================
// 6. loop() — повторюється БЕЗКІНЕЧНО
// ============================================================================
// Один повний цикл: 30° → пауза → 90° → пауза → 150° → пауза = ≈ 3.6 с.
// Кути 30° і 150° навмисно НЕ крайні (0° і 180°), щоб не навантажувати шестерні.
void loop() {
    setServoAngle(30);
    // delay(1200) — процесор «спить» 1.2 с і нічого не робить.
    // АЛЕ метроном LEDC при цьому працює: 1200 / 20 = 60 імпульсів
    // по ≈ 1166 мкс вийде на GPIO4 без жодної участі процесора.
    // Саме це ми й перевіримо логічним аналізатором!
    delay(1200);

    setServoAngle(90);
    delay(1200);   // Ще 60 імпульсів по ≈ 1500 мкс

    setServoAngle(150);
    delay(1200);   // Ще 60 імпульсів по ≈ 1833 мкс
}