/*
 * Lesson 2.5 — Servo 02: smooth non-blocking sweep with millis().
 * Board: ESP32-S3 DevKitC-1 (N16R8), Arduino Core 3.x (pioarduino).
 * Servo signal on GPIO4, 50 Hz, 14-bit LEDC PWM.
 * Sweeps 30 <-> 150 degrees, 1 degree every 20 ms, without delay().
 *
 * ============================================================================
 * СХЕМА ПІДКЛЮЧЕННЯ
 * ============================================================================
 *
 * Дві зони живлення, СПІЛЬНА ЛИШЕ ЗЕМЛЯ:
 *   - зона 3.3 В: ESP32 живиться від USB комп'ютера;
 *   - зона 5 В:   серво живиться від модуля живлення макетки (перемичка на 5V).
 *
 * Дроти серво (SG90 / MG90S):
 *   коричневий / чорний           = GND
 *   червоний (СЕРЕДНІЙ)           = «+» 5 В
 *   помаранчевий / жовтий / білий = Signal
 *   Підказка: найтемніший = GND, середній = «+», найсвітліший = Signal.
 *
 *   1. Модуль живлення +5V   -> шина «+» макетки
 *   2. Модуль живлення GND   -> шина «−» макетки
 *   3. Серво «+» (середній)  -> шина «+» (5 В)
 *   4. Серво GND             -> шина «−»
 *   5. Серво Signal          -> ESP32 GPIO4
 *   6. ESP32 GND             -> шина «−»     (СПІЛЬНА ЗЕМЛЯ — обов'язково!)
 *   7. ESP32 USB             -> комп'ютер
 *
 *   Модуль +5V ---> шина «+» ---> Серво «+»
 *   Модуль GND ---> шина «−» ---> Серво GND
 *                      ^
 *   ESP32 GND ---------+            (спільна земля)
 *   ESP32 GPIO4 ----------------> Серво Signal
 *   ESP32 USB ------------------> Комп'ютер
 *
 * ЗАБОРОНЕНО:
 *   - Серво «+» -> 3V3 або 5V-пін ESP32 (просідання напруги -> перезапуск плати).
 *   - З'єднувати +5V модуля з +5V плати (два джерела «сваряться»).
 *   - Перемикати дроти під напругою.
 *
 * Порядок увімкнення: перевірити дроти -> USB ESP32 -> модуль живлення ON.
 */

// ============================================================================
// 1. ПІДКЛЮЧЕННЯ БІБЛІОТЕК
// ============================================================================

// Arduino.h — Serial, millis(), ledcAttach(), ledcWrite() та інше.
#include <Arduino.h>

// cstdint — типи з точно відомим розміром (uint8_t, uint16_t, uint32_t).
#include <cstdint>

// ============================================================================
// 2. НАЛАШТУВАННЯ (КОНСТАНТИ)
// ============================================================================
// constexpr = значення відоме під час компіляції й ніколи не змінюється.

// Сигнальний провід серво.
constexpr uint8_t SERVO_PIN = 4;

// 50 імпульсів за секунду — стандарт для хобі-серво. Період = 20 мс.
constexpr uint32_t PWM_FREQ_HZ = 50;

// 14 біт = 16 384 поділки на період. Одна поділка ≈ 1.22 мкс.
constexpr uint8_t PWM_RESOLUTION_BITS = 14;

// Період у мікросекундах: 1 000 000 / 50 = 20 000 мкс.
constexpr uint32_t PWM_PERIOD_US = 1000000UL / PWM_FREQ_HZ;

// Кількість поділок: 2^14 = 16 384.
constexpr uint32_t PWM_STEPS = 1UL << PWM_RESOLUTION_BITS;

// Межі імпульсу: 1000 мкс = 0°, 2000 мкс = 180° (обережний діапазон).
constexpr uint16_t SERVO_MIN_US = 1000;
constexpr uint16_t SERVO_MAX_US = 2000;

// Як часто робимо крок у 1°.
// 20 мс — рівно один період PWM: кожен новий імпульс уже має новий кут.
constexpr uint32_t STEP_INTERVAL_MS = 20;

// Межі руху. Навмисно НЕ 0° і 180°, щоб не впиратися в механічні упори.
// Від 30 до 150 = 120 кроків × 20 мс = 2.4 с в один бік, 4.8 с туди-назад.
constexpr int ANGLE_MIN = 30;
constexpr int ANGLE_MAX = 150;

// ============================================================================
// 3. ФУНКЦІЯ «стань на кут angle»
// ============================================================================
// Тут angle має тип int (зі знаком), а не uint8_t, як у Servo 01.
// Причина: у loop() ми додаємо до кута direction = -1, тож теоретично кут
// може стати від'ємним. uint8_t від'ємних не має і «перекрутився» б на 255.
void setServoAngle(int angle) {
    // Подвійний запобіжник: обрізаємо кут до 0…180.
    if (angle < 0) angle = 0;
    if (angle > 180) angle = 180;

    // Кут -> мікросекунди: 0° = 1000, 90° = 1500, 180° = 2000.
    // 1° ≈ 5.56 мкс, тож ширина імпульсу змінюється кроками по 5–6 мкс.
    const uint32_t pulseUs = SERVO_MIN_US
        + (static_cast<uint32_t>(angle) * (SERVO_MAX_US - SERVO_MIN_US)) / 180;

    // Мікросекунди -> поділки LEDC з округленням до найближчого.
    // (У Servo 01 це була окрема функція pulseToDuty(), тут — одним рядком.)
    const uint32_t duty = (pulseUs * PWM_STEPS + PWM_PERIOD_US / 2) / PWM_PERIOD_US;

    // Записуємо число в регістр LEDC — далі апаратура сама формує імпульси.
    // Результат (true/false) тут не перевіряємо: виклик кожні 20 мс,
    // а друк помилки 50 разів за секунду «засмітив» би монітор.
    ledcWrite(SERVO_PIN, duty);
}

// ============================================================================
// 4. setup() — один раз після старту
// ============================================================================
void setup() {
    Serial.begin(115200);

    // Прив'язуємо LEDC-канал і таймер до GPIO4: 50 Гц, 14 біт.
    if (!ledcAttach(SERVO_PIN, PWM_FREQ_HZ, PWM_RESOLUTION_BITS)) {
        Serial.println("ERROR: ledcAttach failed");
        while (true) delay(1000);  // Без PWM далі немає сенсу
    }

    // Стартуємо з центру — найбезпечніше положення.
    setServoAngle(90);
}

// ============================================================================
// 5. loop() — повторюється безкінечно, ДУЖЕ швидко (сотні тисяч разів/с)
// ============================================================================
void loop() {
    // static = «пам'ять між викликами».
    // Звичайна змінна в loop() створювалась би заново щоразу й забувала значення.
    // static створюється ОДИН раз і пам'ятає своє значення між проходами loop().
    static uint32_t lastStepMs = 0;   // Коли востаннє робили крок
    static int angle = 90;            // Поточний командний кут (старт — центр)
    static int direction = +1;        // +1 = рухаємось вгору, -1 = вниз

    // Дивимось на «годинник»: скільки мс минуло від увімкнення плати.
    const uint32_t now = millis();

    // Чи минуло вже 20 мс від попереднього кроку?
    // Чому саме «now - lastStepMs», а не «now >= lastStepMs + 20»?
    // millis() через ≈ 49.7 дня переповнюється й починає з 0 (як одометр).
    // Віднімання беззнакових чисел дає правильну різницю навіть після переповнення.
    if (now - lastStepMs >= STEP_INTERVAL_MS) {
        lastStepMs = now;       // Запам'ятовуємо час цього кроку
        angle += direction;     // Крок на 1° у поточному напрямку

        // Дійшли до верхньої межі — розвертаємось вниз.
        if (angle >= ANGLE_MAX) {
            angle = ANGLE_MAX;
            direction = -1;
        // Дійшли до нижньої межі — розвертаємось вгору.
        } else if (angle <= ANGLE_MIN) {
            angle = ANGLE_MIN;
            direction = +1;
        }

        setServoAngle(angle);   // Даємо LEDC нову команду

        Serial.printf("angle=%d\n", angle);  // Розкоментуй, щоб бачити кут у моніторі (50 рядків/с)
    }

    // ТУТ процесор ВІЛЬНИЙ!
    // Якщо 20 мс ще не минуло — loop() просто завершується й одразу починається знову.
    // Сюди можна дописати інші справи (кнопки, LED, датчики) —
    // вони працюватимуть «одночасно» з рухом серво.
}